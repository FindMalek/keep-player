import { appShortcuts, lyricsShortcuts } from "../apps/player/src/app-shortcuts";
import type { Shortcut, ShortcutGroup } from "../apps/player/src/lib/shortcuts";

// Regenerates docs/shortcuts.md from the shortcut registry (the same list the `?` sheet shows); `--check` fails when
// the file is out of date (CI).
// Every action is a no-op: only the list matters here, so a new action never needs adding.
const stub = new Proxy({}, { get: () => () => undefined }) as never;
const shortcuts: Shortcut[] = [...appShortcuts(stub), ...lyricsShortcuts(() => true, 250)];

const SYMBOLS: Record<string, string> = {
  mod: "⌘/ctrl",
  shift: "⇧",
  alt: "⌥/alt",
  arrowup: "↑",
  arrowdown: "↓",
  arrowleft: "←",
  arrowright: "→",
  escape: "esc",
  enter: "enter",
  space: "space",
  delete: "delete",
  backspace: "⌫",
};
const keys = (binding: string) =>
  binding
    .toLowerCase()
    .split(" ")
    .map((step) =>
      step
        .split("+")
        .map((key) => `\`${SYMBOLS[key] ?? key}\``)
        .join(" "),
    )
    .join(" then ");

const GROUPS: [ShortcutGroup, string][] = [
  ["playback", "Playback"],
  ["navigation", "Navigation"],
  ["panels", "Panels"],
  ["lists", "Lists (when a list or grid has focus)"],
];

const lines = [
  "# Keyboard shortcuts",
  "",
  "Press `?` in the app for this list, searchable, with what applies right now highlighted. Every shortcut can be",
  "rebound there (pencil icon); a rebound key shows everywhere the app shows the key.",
  "",
  "<!-- generated by `bun scripts/shortcuts-docs.ts` from apps/player/src/app-shortcuts.ts; don't edit by hand -->",
];
for (const [group, title] of GROUPS) {
  const items = shortcuts.filter((shortcut) => shortcut.group === group && !shortcut.id.startsWith("jump-"));
  if (!items.length) continue;
  lines.push("", `## ${title}`, "", "| keys | action |", "|---|---|");
  for (const item of items) lines.push(`| ${item.keys.map(keys).join(" or ")} | ${item.label} |`);
  if (group === "playback") lines.push("| `0` … `9` | jump to 0 % … 90 % of the song |");
}
const expected = `${lines.join("\n")}\n`;

const path = "docs/shortcuts.md";
if (process.argv.includes("--check")) {
  if (
    (await Bun.file(path)
      .text()
      .catch(() => "")) !== expected
  ) {
    console.error(`${path} is out of date: run bun scripts/shortcuts-docs.ts`);
    process.exit(1);
  }
  console.log(`${path}: up to date`);
} else {
  await Bun.write(path, expected);
  console.log(`wrote ${path}`);
}
